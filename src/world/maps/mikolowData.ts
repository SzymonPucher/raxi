function pointInPolygon(x: number, z: number, polygon: Array<[number, number]>): boolean {
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const xi = polygon[i][0];
    const zi = polygon[i][1];
    const xj = polygon[j][0];
    const zj = polygon[j][1];
    const intersect =
      zi > z !== zj > z && x < ((xj - xi) * (z - zi)) / (zj - zi + 1e-12) + xi;
    if (intersect) inside = !inside;
  }
  return inside;
}

function getMikolowDistrictAt(x: number, z: number, fallback: DistrictId): DistrictId {
  for (const gz of MIKOLOW_GREEN_ZONES) {
    if (gz.kind === 'park' && pointInPolygon(x, z, gz.polygon)) {
      return 'park';
    }
  }
  return fallback;
}

/**
 * Real-world geospatial map of Mikołów, Poland centered on Rynek (50.1704°N, 18.9039°E).
 * Built on ONE unified EU-DEM 25m HeightMap with OSM roads, sidewalks, rail corridor,
 * green zones, 16 landmarks, 4 garages, 5 jump ramps, and authentic Silesian architecture.
 */
export function createMikolowMapDefinition(): MapDefinition {
  const heightMap = createMikolowHeightMap();

  const nodes: RoadNode[] = RAW_NODES.map(([id, x, z, district, tl]) => ({
    id,
    x,
    y: heightMap.sample(x, z),
    z,
    district,
    hasTrafficLight: tl === 1,
  }));

  const edges: Omit<RoadEdge, 'length'>[] = RAW_EDGES.map((raw, idx) => ({
    id: `mk_e_${idx}`,
    from: raw[0],
    to: raw[1],
    name: raw[2],
    roadType: raw[3],
    lanesPerDir: raw[4],
    speedLimit: raw[5],
    width: raw[6],
    sidewalkWidth: raw[7],
    isShortcut: raw[8] === 1 ? true : undefined,
    isOneWay: raw[9] === 1 ? true : undefined,
  }));

  const graph = new RoadGraph(nodes, edges);

  const greenZones: GreenZoneDef[] = MIKOLOW_GREEN_ZONES.map((gz) => ({
    ...gz,
    polygon: gz.polygon.map(([px, pz]) => [px, pz] as [number, number]),
  }));

  const railLines: RailLineDef[] = MIKOLOW_RAIL_LINES.map((rl) => ({
    points: rl.points.map(([px, pz]) => [px, pz] as [number, number]),
  }));

  const landmarks: LandmarkDef[] = MIKOLOW_LANDMARKS.map((lm) => {
    const shape = MIKOLOW_LANDMARK_SHAPES[lm.id];
    if (!shape) return { ...lm };
    return {
      ...lm,
      footprintParts: shape.footprintParts.map((p) => ({
        ...p,
        polygon: p.polygon.map(([px, pz]) => [px, pz] as [number, number]),
      })),
      parkingLots: shape.parkingLots?.map((l) => ({
        ...l,
        polygon: l.polygon.map(([px, pz]) => [px, pz] as [number, number]),
      })),
    };
  });

  // Polygons that must stay free of generic filler buildings (real landmark shapes + parking lots)
  const reservedPolygons: Array<Array<[number, number]>> = [];
  for (const lm of landmarks) {
    for (const p of lm.footprintParts ?? []) reservedPolygons.push(p.polygon);
    for (const l of lm.parkingLots ?? []) reservedPolygons.push(l.polygon);
  }
  const isInsideReserved = (x: number, z: number, w: number, d: number): boolean =>
    reservedPolygons.some(
      (poly) =>
        pointInPolygon(x, z, poly) ||
        pointInPolygon(x + w * 0.4, z + d * 0.4, poly) ||
        pointInPolygon(x - w * 0.4, z - d * 0.4, poly)
    );
  const garages: GarageDef[] = MIKOLOW_GARAGES.map((g) => ({ ...g }));

  const ramps: RampDef[] = MIKOLOW_RAW_RAMPS.map((r) => ({
    ...r,
    y: heightMap.sample(r.x, r.z),
  }));

  const customBuildings: CustomBuildingDef[] = RAW_BUILDINGS.filter(
    ([x, z, w, d]) => !isInsideReserved(x, z, w, d)
  ).map(
    ([x, z, w, d, h, rotY, color, roofColor, style]) => ({
      x,
      z,
      w,
      d,
      h,
      rotY,
      color,
      roofColor,
      style,
    })
  );

  // Sidewalk pickup/dropoff spots: all 16 landmarks + real Polish street addresses
  const sidewalkSpots: SidewalkSpot[] = [];

  for (const lm of landmarks) {
    const nearest = graph.projectPoint(lm.curbX, lm.curbZ, 0, -1, 80);
    sidewalkSpots.push({
      x: lm.curbX,
      y: heightMap.sample(lm.curbX, lm.curbZ),
      z: lm.curbZ,
      edgeId: nearest?.edge.id ?? graph.edges[0].id,
      district: lm.district,
      address: lm.name,
      landmarkId: lm.id,
    });
  }

  const streetCounters = new Map<string, number>();

  for (let i = 0; i < graph.edges.length; i++) {
    const e = graph.edges[i];
    if (e.roadType === 'highway' || e.roadType === 'bridge' || e.isShortcut) continue;
    const a = graph.getNode(e.from);
    const b = graph.getNode(e.to);
    if (!a || !b) continue;

    const dx = b.x - a.x;
    const dz = b.z - a.z;
    const len = Math.hypot(dx, dz);
    if (len < 36) continue;

    const rx = -dz / len;
    const rz = dx / len;
    const sw = e.sidewalkWidth ?? 2.2;
    const offset = e.width * 0.5 + Math.max(1.2, Math.min(2.2, sw * 0.55));
    const samples = len >= 90 ? [0.3, 0.7] : [0.5];
    const streetLabel = e.name ?? 'ul. Mikołowska';

    for (const t of samples) {
      const side = (i % 2 === 0 ? 1 : -1) * (t > 0.5 ? 1 : -1);
      const sx = a.x + dx * t + rx * offset * side;
      const sz = a.z + dz * t + rz * offset * side;

      if (Math.abs(sx) > MIKOLOW_WORLD_HALF_SIZE - 40 || Math.abs(sz) > MIKOLOW_WORLD_HALF_SIZE - 40) {
        continue;
      }
      if (garages.some((g) => Math.hypot(g.x - sx, g.z - sz) < 24)) continue;
      if (
        landmarks.some(
          (lm) =>
            Math.abs(lm.x - sx) < lm.footprintW * 0.5 + 4 &&
            Math.abs(lm.z - sz) < lm.footprintD * 0.5 + 4
        )
      ) {
        continue;
      }

      const prevNum = streetCounters.get(streetLabel) ?? 0;
      const houseNum = prevNum + 2 + ((i * 3) % 5);
      streetCounters.set(streetLabel, houseNum);

      const spotX = Number(sx.toFixed(2));
      const spotZ = Number(sz.toFixed(2));
      const sy = heightMap.sample(spotX, spotZ);
      sidewalkSpots.push({
        x: spotX,
        y: sy,
        z: spotZ,
        edgeId: e.id,
        district: getMikolowDistrictAt(spotX, spotZ, t < 0.5 ? a.district : b.district),
        address: `${streetLabel} ${houseNum}`,
      });
    }
  }

  return {
    id: 'mikolow',
    displayName: 'Mikołów, Poland',
    // Spawn on Rynek / ul. św. Wojciecha in the right-hand lane facing East toward Bazylika św. Wojciecha
    spawn: { x: 63.3, z: 131.9, yaw: -1.4825 },
    graph,
    heightMap,
    landmarks,
    garages,
    ramps,
    sidewalkSpots,
    greenZones,
    railLines,
    customBuildings,
    disableDefaultGridBuildings: true,
    parkBounds: { minX: -964, maxX: -190, minZ: 210, maxZ: 680 },
    worldHalfSize: MIKOLOW_WORLD_HALF_SIZE,
    cityCoreHalfSize: 650,
  };
}
