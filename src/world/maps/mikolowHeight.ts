function catmullRom(p0: number, p1: number, p2: number, p3: number, t: number): number {
  const t2 = t * t;
  const t3 = t2 * t;
  return (
    0.5 *
    (2 * p1 +
      (-p0 + p2) * t +
      (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2 +
      (-p0 + 3 * p1 - 3 * p2 + p3) * t3)
  );
}

function sampleDemCell(ix: number, iz: number): number {
  const cx = Math.max(0, Math.min(MIKOLOW_DEM_GRID_SIZE - 1, ix));
  const cz = Math.max(0, Math.min(MIKOLOW_DEM_GRID_SIZE - 1, iz));
  return MIKOLOW_DEM_HEIGHTS[cz * MIKOLOW_DEM_GRID_SIZE + cx];
}

/**
 * Smooth Catmull-Rom bicubic interpolation over the real Mikołów EU-DEM elevation grid.
 * Preserves authentic Upper Silesian hill relief (57.84m) with C1-continuous drivable grades.
 */
export function getMikolowTerrainHeight(x: number, z: number): number {
  const span = MIKOLOW_DEM_HALF_SIZE * 2;
  const maxIdx = MIKOLOW_DEM_GRID_SIZE - 1;
  const clampedX = Math.max(-MIKOLOW_DEM_HALF_SIZE, Math.min(MIKOLOW_DEM_HALF_SIZE, x));
  const clampedZ = Math.max(-MIKOLOW_DEM_HALF_SIZE, Math.min(MIKOLOW_DEM_HALF_SIZE, z));
  const u = ((clampedX + MIKOLOW_DEM_HALF_SIZE) / span) * maxIdx;
  const v = ((clampedZ + MIKOLOW_DEM_HALF_SIZE) / span) * maxIdx;

  const ix = Math.floor(u);
  const iz = Math.floor(v);
  const fx = Math.max(0, Math.min(1, u - ix));
  const fz = Math.max(0, Math.min(1, v - iz));

  const r0 = catmullRom(
    sampleDemCell(ix - 1, iz - 1),
    sampleDemCell(ix, iz - 1),
    sampleDemCell(ix + 1, iz - 1),
    sampleDemCell(ix + 2, iz - 1),
    fx
  );
  const r1 = catmullRom(
    sampleDemCell(ix - 1, iz),
    sampleDemCell(ix, iz),
    sampleDemCell(ix + 1, iz),
    sampleDemCell(ix + 2, iz),
    fx
  );
  const r2 = catmullRom(
    sampleDemCell(ix - 1, iz + 1),
    sampleDemCell(ix, iz + 1),
    sampleDemCell(ix + 1, iz + 1),
    sampleDemCell(ix + 2, iz + 1),
    fx
  );
  const r3 = catmullRom(
    sampleDemCell(ix - 1, iz + 2),
    sampleDemCell(ix, iz + 2),
    sampleDemCell(ix + 1, iz + 2),
    sampleDemCell(ix + 2, iz + 2),
    fx
  );

  return Math.max(0, catmullRom(r0, r1, r2, r3, fz));
}

export function createMikolowHeightMap(): HeightMap {
  return new HeightMap(MIKOLOW_WORLD_HALF_SIZE, 224, getMikolowTerrainHeight);
}
